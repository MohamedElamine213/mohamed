// ========== دوال الحجز والسيارات ==========
function toggleCarPanel() {
  const panel = document.getElementById('carPanel');
  const chk = document.getElementById('carCheck');
  if (panel && chk) {
    panel.classList.toggle('open', chk.checked);
    if (!chk.checked) {
      selectedCarPrice = 0;
      selectedCarType = '';
      updateCarSummary();
    }
  }
}

function selectCar(el, name, type, price) {
  document.querySelectorAll('.car-card').forEach(c => c.classList.remove('selected'));
  el.classList.add('selected');
  selectedCarPrice = price;
  selectedCarType = `${name} (${type})`;
  updateCarSummary();
}

function setDriver(mode) {
  driverMode = mode;
  document.getElementById('drvSelf')?.classList.toggle('active', mode === 'self');
  document.getElementById('drvWith')?.classList.toggle('active', mode === 'driver');
  updateCarSummary();
}

function updateCarSummary() {
  const summary = document.getElementById('carSummary');
  if (!summary) return;
  if (!selectedCarPrice) {
    summary.classList.remove('show');
    return;
  }
  const days = parseInt(document.getElementById('carDays')?.value) || 1;
  const driverAdd = driverMode === 'driver' ? 3000 : 0;
  const total = (selectedCarPrice + driverAdd) * days;
  document.getElementById('csType').textContent = selectedCarType;
  document.getElementById('csDay').textContent = (selectedCarPrice + driverAdd).toLocaleString() + ' دج';
  document.getElementById('csDays').textContent = days + ' يوم';
  document.getElementById('csDriver').textContent = driverMode === 'driver' ? 'مع سائق (+3,000 دج)' : 'بدون سائق';
  document.getElementById('csTotal').textContent = total.toLocaleString() + ' دج';
  summary.classList.add('show');
}

function submitBooking() {
  const user = JSON.parse(localStorage.getItem('t213_user') || 'null');
  const name = document.getElementById('bName')?.value || '';
  const phone = document.getElementById('bPhone')?.value || '';
  const dest = document.getElementById('bDest')?.value || '';
  const date = document.getElementById('bDate')?.value || '';
 
  if (!name || !phone || !dest || !date) {
    showToast('⚠️ يرجى ملء جميع الحقول الإلزامية (*)', 'err');
    return;
  }
 
  const booking = {
    id: 'T213-' + Date.now(),
    name: name,
    phone: phone,
    email: document.getElementById('bEmail')?.value || '',
    dest: dest,
    date: date,
    people: document.getElementById('bPeople')?.value || '',
    pkg: document.getElementById('bPkg')?.value || '',
    note: document.getElementById('bNote')?.value || '',
    status: 'مؤكد ✓',
    createdAt: new Date().toLocaleDateString('ar-DZ'),
    userEmail: user ? user.email : null
  };
 
  const carCheck = document.getElementById('carCheck');
  if (carCheck && carCheck.checked && selectedCarType) {
    const days = parseInt(document.getElementById('carDays')?.value) || 1;
    booking.car = {
      type: selectedCarType,
      days: days,
      driver: driverMode,
      price: (selectedCarPrice + (driverMode === 'driver' ? 3000 : 0)) * days
    };
  }
 
  const bookings = JSON.parse(localStorage.getItem('t213_bookings') || '[]');
  bookings.push(booking);
  localStorage.setItem('t213_bookings', JSON.stringify(bookings));
  localStorage.setItem('t213_lastBooking', JSON.stringify(booking));
 
  window.location.href = 'booking-success.html';
}

